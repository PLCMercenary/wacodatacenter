const assert=require('node:assert/strict');
const calendar=require('../static/js/events.js');
const meeting={date:'2026-10-13',time:'6:00 PM',title:'Council, community; meeting',location:'501 E. Craven Ave.',notes:'Line one\nLine two'};
assert.equal(calendar.localToUTC('2026-10-13',18*60).toISOString(),'2026-10-13T23:00:00.000Z');
assert.equal(calendar.localToUTC('2026-12-08',18*60).toISOString(),'2026-12-09T00:00:00.000Z');
assert.equal(calendar.localToUTC('2026-03-08',18*60).toISOString(),'2026-03-08T23:00:00.000Z');
assert.equal(calendar.localToUTC('2026-11-01',18*60).toISOString(),'2026-11-02T00:00:00.000Z');
assert.equal(calendar.sessions('3:00 PM / 6:00 PM').length,2);
assert.deepEqual(calendar.sessions('9:00 AM – 1:00 PM')[0],{label:'9:00 AM – 1:00 PM',start:540,end:780,estimated:false});
const overnight=calendar.sessions('11:30 PM – 1:00 AM')[0];
assert.equal(calendar.span({...meeting,date:'2026-12-31'},overnight).end,'2027-01-01T07:00:00.000Z');
const unknown=calendar.sessions('TBD')[0];
assert.deepEqual(calendar.span({...meeting,date:'2026-12-31'},unknown),{start:'2026-12-31',end:'2027-01-01',allDay:true});
assert.equal(calendar.sessions('25:90 PM')[0].start,null);
const session=calendar.sessions(meeting.time)[0];
const ics=calendar.ics(meeting,session);
assert.match(ics,/DTSTART:20261013T230000Z/);
assert.match(ics,/SUMMARY:Council\\, community\\; meeting/);
assert.match(ics,/Line one\\nLine two/);
assert.match(ics,/DTEND:20261014T000000Z/);
assert.equal(ics.match(/UID:.+/)[0],calendar.ics(meeting,session).match(/UID:.+/)[0]);
const long=calendar.ics({...meeting,title:'é'.repeat(200)},session);
for(const line of long.split('\r\n'))assert.ok(Buffer.byteLength(line)<=75);
const google=new URL(calendar.url('google',meeting,session));
assert.equal(google.searchParams.get('dates'),'20261013T230000Z/20261014T000000Z');
assert.equal(google.searchParams.get('ctz'),'America/Chicago');
const outlook=new URL(calendar.url('outlook-work',meeting,session));
assert.equal(outlook.searchParams.get('startdt'),'2026-10-13T23:00:00.000Z');
const allDay=new URL(calendar.url('google',{...meeting,date:'2026-12-31'},unknown));
assert.equal(allDay.searchParams.get('dates'),'20261231/20270101');
console.log('Calendar checks passed, including daylight saving, multiple sessions, all-day reminders, and ICS escaping/folding.');
